/**
 * GrokHooksManager - Hook management for xAI's Grok Build CLI
 *
 * Unlike Kimi (flat [[hooks]] tables in config.toml) or Codex (nested TOML), Grok
 * loads DISCRETE JSON hook files from <GROK_HOME>/hooks/*.json. Every file in that
 * directory is trusted, and the shape is Claude-like:
 *
 *   {
 *     "hooks": {
 *       "PreToolUse": [
 *         { "matcher": "*", "hooks": [ { "type": "command", "command": "...", "timeout": 30 } ] }
 *       ]
 *     }
 *   }
 *
 * One file per toggleable group means install/remove is a whole-file write/unlink —
 * we never rewrite a user's own hook files, and there is no parser to get wrong.
 *
 * Hook I/O contract: Grok's stdin JSON uses camelCase (`toolName`, `toolInput`,
 * `sessionId`, `hookEventName`) where Claude/Kimi use snake_case. The three scripts
 * below therefore read camelCase FIRST with a snake_case fallback, and the title
 * gate is a thin wrapper that normalizes the payload before delegating to the SHARED
 * title-gate script (same body as Claude/Codex/Kimi) so the gate logic stays in one
 * place.
 *
 * What we install (three independently toggleable groups):
 *  1. notifications — Stop -> claude_finished, PermissionDenied -> confirmation_needed.
 *     `Notification` is deliberately NOT hooked (ambiguous: it is not necessarily a
 *     request for the user), mirroring the Kimi decision.
 *  2. titleGate — PreToolUse (matcher "*") -> the shared non-blocking title reminder.
 *     It NEVER emits a permissionDecision, so it can never deadlock a terminal.
 *  3. fileChange — PostToolUse (matcher "search_replace|Write|Edit") -> posts a
 *     file_edited event so the CodeAgentSwarm diff viewer tracks Grok's edits.
 *
 * checkHooksStatus is a pure disk read (no subprocess), per the e2e-sandbox rule.
 */

const fs = require('fs');
const path = require('path');
const os = require('os');
const titleGateScript = require('./title-gate-script');

// One JSON file per group under <GROK_HOME>/hooks/.
const HOOK_FILES = {
    notifications: 'codeagentswarm-notify.json',
    titleGate: 'codeagentswarm-title-gate.json',
    fileChange: 'codeagentswarm-filechange.json',
};

class GrokHooksManager {
    constructor(options = {}) {
        const dataRoot = (process.env.GROK_HOME || '').trim() || path.join(os.homedir(), '.grok');
        this.hooksJsonDir = path.join(dataRoot, 'hooks');
        this.isDevMode = options.isDevMode || false;
        this.webhookPort = this.isDevMode ? 45783 : 45782;
        this.hooksScriptsDir = path.join(os.homedir(), '.codeagentswarm', 'hooks');
        this.isWindows = process.platform === 'win32';

        // Exposed for HookSystemPreferences status rows.
        this.settingsPath = this.hooksJsonDir;

        console.log(`[GrokHooksManager] Initialized (${this.isDevMode ? 'DEV' : 'PROD'} mode, hooks dir: ${this.hooksJsonDir})`);
    }

    /** Substrings that uniquely identify OUR hook files (in their command). */
    static get GATE_TAG() { return 'grok-title-gate-hook'; }
    static get NOTIFY_TAG() { return 'grok-notify-hook'; }
    static get FILECHANGE_TAG() { return 'grok-edit-write-hook'; }

    toUnixPath(filePath) {
        return filePath.replace(/\\/g, '/');
    }

    async ensureHooksDirectory() {
        if (!fs.existsSync(this.hooksScriptsDir)) {
            fs.mkdirSync(this.hooksScriptsDir, { recursive: true });
        }
    }

    async ensureConfigDirectory() {
        if (!fs.existsSync(this.hooksJsonDir)) {
            fs.mkdirSync(this.hooksJsonDir, { recursive: true });
        }
    }

    // ============================================================
    // Hook scripts on disk
    // ============================================================

    /**
     * The Grok title-gate wrapper. Grok's stdin JSON is camelCase; the SHARED
     * title-gate script greps snake_case (`tool_name`, `session_id`), so the wrapper
     * rewrites the key names and pipes the payload straight through. Keeping the
     * gate logic in the shared script means the invocation caps / fail-open
     * behaviour stay identical across every agent.
     */
    getUnixTitleGateScript() {
        const sharedPath = this.toUnixPath(path.join(this.hooksScriptsDir, 'title-gate-hook.sh'));
        return `#!/bin/bash
# ============================================================================
# grok-title-gate-hook.sh
# Auto-generated by CodeAgentSwarm - Do not edit manually
#
# Grok Build PreToolUse wrapper:
#  1) camelCase stdin → snake_case for the shared title-gate script
#  2) shared script stdout: rewrite Claude event names (PreToolUse) to Grok's
#     lowercase wire dialect (pre_tool_use) so additionalContext is not dropped
# Fail-open: any problem exits 0 with no output (= allow).
# ============================================================================

INPUT=$(head -c 262144)
[ -z "$INPUT" ] && exit 0

NORMALIZED=$(printf '%s' "$INPUT" | sed 's/"toolName"/"tool_name"/g; s/"toolInput"/"tool_input"/g; s/"sessionId"/"session_id"/g; s/"hookEventName"/"hook_event_name"/g')

OUT=$(printf '%s' "$NORMALIZED" | /bin/bash '${sharedPath}' 2>/dev/null) || exit 0
[ -z "$OUT" ] && exit 0
# Grok's hookEventName VALUES are lowercase ("pre_tool_use"); the shared Claude
# script emits PascalCase "PreToolUse" inside hookSpecificOutput.
printf '%s' "$OUT" | sed 's/"PreToolUse"/"pre_tool_use"/g; s/"PostToolUse"/"post_tool_use"/g; s/"Stop"/"stop"/g'
exit 0
`;
    }

    getWindowsTitleGateScript() {
        const sharedPath = this.toUnixPath(path.join(this.hooksScriptsDir, 'title-gate-hook.ps1'));
        return `# ============================================================================
# grok-title-gate-hook.ps1
# Auto-generated by CodeAgentSwarm - Do not edit manually
#
# Grok Build PreToolUse wrapper: normalize stdin + rewrite stdout event names
# to Grok's lowercase dialect so additionalContext is not silently ignored.
# ============================================================================
$ErrorActionPreference = 'SilentlyContinue'
try {
    $inputJson = [Console]::In.ReadToEnd()
    if (-not $inputJson) { exit 0 }

    $normalized = $inputJson.
        Replace('"toolName"', '"tool_name"').
        Replace('"toolInput"', '"tool_input"').
        Replace('"sessionId"', '"session_id"').
        Replace('"hookEventName"', '"hook_event_name"')

    $out = $normalized | & powershell.exe -ExecutionPolicy Bypass -File '${sharedPath}' 2>$null
    if (-not $out) { exit 0 }
    $text = if ($out -is [array]) { $out -join '' } else { [string]$out }
    $text = $text.
        Replace('"PreToolUse"', '"pre_tool_use"').
        Replace('"PostToolUse"', '"post_tool_use"').
        Replace('"Stop"', '"stop"')
    Write-Output $text
} catch { }
exit 0
`;
    }

    /**
     * Write the shared title-gate script (same body as Claude/Codex/Kimi) plus the
     * Grok camelCase wrapper, and return the wrapper's path.
     */
    createTitleGateScript() {
        if (this.isWindows) {
            const sharedPath = path.join(this.hooksScriptsDir, 'title-gate-hook.ps1');
            fs.writeFileSync(sharedPath, titleGateScript.getPowerShellTitleGateScript());
            const wrapperPath = path.join(this.hooksScriptsDir, 'grok-title-gate-hook.ps1');
            fs.writeFileSync(wrapperPath, this.getWindowsTitleGateScript());
            return wrapperPath;
        }
        const sharedPath = path.join(this.hooksScriptsDir, 'title-gate-hook.sh');
        fs.writeFileSync(sharedPath, titleGateScript.getBashTitleGateScript(), { mode: 0o755 });
        const wrapperPath = path.join(this.hooksScriptsDir, 'grok-title-gate-hook.sh');
        fs.writeFileSync(wrapperPath, this.getUnixTitleGateScript(), { mode: 0o755 });
        return wrapperPath;
    }

    /**
     * The notification script: one script for both notification events. It reads the
     * camelCase stdin JSON (snake_case fallback), maps the event to a CAS webhook
     * payload, and always exits 0. CAS-ONLY: outside a CodeAgentSwarm terminal it
     * prints nothing and exits. Dependency-free (sed, no jq).
     */
    getUnixNotifyScript() {
        // Grok's wire envelope is camelCase and the hookEventName VALUE is lowercase
        // ("stop", "permission_denied") — see ~/.grok/docs/user-guide/10-hooks.md
        // "camelCase input" / GROK_HOOK_EVENT. Matching only PascalCase "Stop" silently
        // no-ops every turn-end notification. Accept both casings + GROK_HOOK_EVENT.
        return `#!/bin/bash
# ============================================================================
# grok-notify-hook.sh
# Auto-generated by CodeAgentSwarm - Do not edit manually
#
# Grok Build lifecycle hook: maps Stop / PermissionDenied events to
# CodeAgentSwarm desktop notifications. Always exits 0 (fail-open).
#
# Notification is IGNORED on purpose: its meaning is ambiguous in Grok, and a
# false "needs your confirmation" toast is worse than a missing one.
#
# Event names: Grok sends hookEventName as LOWERCASE ("stop"). PascalCase
# "Stop" is kept so Claude-compat rewrites and older envelopes still match.
# ============================================================================

TERM_ID="\${CODEAGENTSWARM_CURRENT_QUADRANT:-}"
[ -z "$TERM_ID" ] && exit 0

# Driver-backed Chat receives the authoritative turn/permission events straight
# from the ACP driver; this global hook must not double-report them (task #12330).
if [ -n "\${CODEAGENTSWARM_DRIVER_CHAT:-}" ]; then
    exit 0
fi

INPUT=$(head -c 65536)

# Grok's stdin JSON is camelCase; snake_case is kept as a fallback.
EVENT=$(printf '%s' "$INPUT" | sed -n 's/.*"hookEventName"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p' | head -1)
[ -z "$EVENT" ] && EVENT=$(printf '%s' "$INPUT" | sed -n 's/.*"hook_event_name"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p' | head -1)
# Env fallback documented by Grok (GROK_HOOK_EVENT=stop / pre_tool_use / …).
[ -z "$EVENT" ] && EVENT="\${GROK_HOOK_EVENT:-}"
TOOL=$(printf '%s' "$INPUT" | sed -n 's/.*"toolName"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p' | head -1)
[ -z "$TOOL" ] && TOOL=$(printf '%s' "$INPUT" | sed -n 's/.*"tool_name"[[:space:]]*:[[:space:]]*"\\([^"]*\\)".*/\\1/p' | head -1)
[ -z "$TOOL" ] && TOOL="grok-action"

# Normalize to a single lowercase token so Stop/stop/STOP and PermissionDenied
# /permission_denied all hit the same branch.
EVENT_LC=$(printf '%s' "$EVENT" | tr '[:upper:]' '[:lower:]')

case "$EVENT_LC" in
  stop)
    BODY="{\\"type\\":\\"claude_finished\\",\\"terminalId\\":\\"$TERM_ID\\",\\"agent\\":\\"grok\\"}"
    ;;
  permissiondenied|permission_denied)
    BODY="{\\"type\\":\\"confirmation_needed\\",\\"terminalId\\":\\"$TERM_ID\\",\\"agent\\":\\"grok\\",\\"tool\\":\\"$TOOL\\"}"
    ;;
  *)
    exit 0
    ;;
esac

# Post to THIS instance's webhook port (injected by CodeAgentSwarm); the fallbacks keep the
# legacy dev-first (45783) / prod (45782) behaviour for terminals opened outside the app.
curl -X POST "http://127.0.0.1:\${CODEAGENTSWARM_WEBHOOK_PORT:-45783}/webhook" -H "Content-Type: application/json" \\
  -d "$BODY" --silent --fail --max-time 2 >/dev/null 2>&1 || \\
curl -X POST "http://127.0.0.1:\${CODEAGENTSWARM_WEBHOOK_PORT:-45782}/webhook" -H "Content-Type: application/json" \\
  -d "$BODY" --silent --max-time 2 >/dev/null 2>&1 || true

exit 0
`;
    }

    getWindowsNotifyScript() {
        return `# ============================================================================
# grok-notify-hook.ps1
# Auto-generated by CodeAgentSwarm - Do not edit manually
# Grok sends hookEventName as lowercase ("stop"); normalize before matching.
# ============================================================================
$ErrorActionPreference = 'SilentlyContinue'
try {
    $terminalId = $env:CODEAGENTSWARM_CURRENT_QUADRANT
    if (-not $terminalId) { exit 0 }

    # Driver-backed Chat: the ACP driver already reports turn ends and permission
    # requests; this global hook must not double-report them.
    if ($env:CODEAGENTSWARM_DRIVER_CHAT) { exit 0 }

    $inputJson = [Console]::In.ReadToEnd()
    $data = $null
    if ($inputJson) {
        try { $data = $inputJson | ConvertFrom-Json } catch { $data = $null }
    }

    # Grok's payload is camelCase; snake_case + GROK_HOOK_EVENT are fallbacks.
    $eventName = $null
    if ($data -and $data.hookEventName) { $eventName = [string]$data.hookEventName }
    elseif ($data -and $data.hook_event_name) { $eventName = [string]$data.hook_event_name }
    elseif ($env:GROK_HOOK_EVENT) { $eventName = [string]$env:GROK_HOOK_EVENT }
    if (-not $eventName) { exit 0 }

    $tool = 'grok-action'
    if ($data -and $data.toolName) { $tool = [string]$data.toolName }
    elseif ($data -and $data.tool_name) { $tool = [string]$data.tool_name }

    $eventLc = $eventName.ToLowerInvariant()
    # Every other event, Notification included, falls through to the no-op default.
    switch ($eventLc) {
        'stop' { $payload = @{ type = 'claude_finished'; terminalId = "$terminalId"; agent = 'grok' } }
        'permissiondenied' { $payload = @{ type = 'confirmation_needed'; terminalId = "$terminalId"; agent = 'grok'; tool = "$tool" } }
        'permission_denied' { $payload = @{ type = 'confirmation_needed'; terminalId = "$terminalId"; agent = 'grok'; tool = "$tool" } }
        default { exit 0 }
    }
    $body = $payload | ConvertTo-Json -Compress

    # Post to THIS instance's webhook port when CodeAgentSwarm injected it; otherwise fall
    # back to the legacy dev-first (45783) / prod (45782) probe for older builds.
    $ports = if (($casPort = $env:CODEAGENTSWARM_WEBHOOK_PORT -as [int])) { @($casPort) } else { @(45783, 45782) }
    foreach ($port in $ports) {
        try {
            Invoke-RestMethod -Uri "http://127.0.0.1:$port/webhook" -Method POST -ContentType 'application/json' -Body $body -TimeoutSec 2 -ErrorAction Stop | Out-Null
            exit 0
        } catch { continue }
    }
} catch { }
exit 0
`;
    }

    /**
     * File-change script: same file_edited payload Claude's edit-write hook posts, so
     * the existing FileChangeTracker/diff viewer renders it unchanged. Grok's tool
     * input is camelCase and the path key varies by tool (`file_path` for the Claude
     * aliases, `path`/`TargetFile` for the native search_replace), so all are tried.
     * If jq is missing or fields are absent, it exits 0.
     */
    getUnixFileChangeScript() {
        return `#!/bin/bash
# ============================================================================
# grok-edit-write-hook.sh
# Auto-generated by CodeAgentSwarm - Do not edit manually
#
# PostToolUse hook (matcher search_replace|Write|Edit): posts a file_edited event
# so the CodeAgentSwarm diff viewer tracks Grok's file changes. Always exits 0.
# ============================================================================

TERM_ID="\${CODEAGENTSWARM_CURRENT_QUADRANT:-}"
[ -z "$TERM_ID" ] && exit 0
command -v jq >/dev/null 2>&1 || exit 0

TMP=$(mktemp)
trap "rm -f '$TMP'" EXIT

# camelCase first (Grok), snake_case second (Claude-shaped payloads).
# Grok PostToolUse result field is toolResult (docs) — not Claude's tool_response.
jq -c "
  (.toolInput // .tool_input // {}) as \\$in |
  (.toolResult // .tool_result // .toolResponse // .tool_response // {}) as \\$out |
  {
    type: \\"file_edited\\",
    terminalId: \\"$TERM_ID\\",
    toolName: (.toolName // .tool_name),
    filePath: (\\$in.file_path // \\$in.path // \\$in.filePath // \\$in.TargetFile // null),
    content: (\\$in.content // \\$in.CodeContent // null),
    oldString: (\\$in.old_string // \\$in.oldString // null),
    newString: (\\$in.new_string // \\$in.newString // null),
    originalContent: (\\$out.returnDisplay.originalContent // \\$out.originalContent // null),
    newContent: (\\$out.returnDisplay.newContent // \\$out.newContent // null)
  }" > "$TMP" 2>/dev/null || exit 0

# Drop payloads with no file path (unexpected shape) instead of confusing the tracker.
grep -q '"filePath":null' "$TMP" && exit 0

# Post to THIS instance's webhook port (injected by CodeAgentSwarm); the fallbacks keep the
# legacy dev-first (45783) / prod (45782) behaviour for terminals opened outside the app.
curl -X POST "http://127.0.0.1:\${CODEAGENTSWARM_WEBHOOK_PORT:-45783}/webhook" -H "Content-Type: application/json" \\
  -d @"$TMP" --silent --fail --max-time 2 >/dev/null 2>&1 || \\
curl -X POST "http://127.0.0.1:\${CODEAGENTSWARM_WEBHOOK_PORT:-45782}/webhook" -H "Content-Type: application/json" \\
  -d @"$TMP" --silent --max-time 2 >/dev/null 2>&1 || true

exit 0
`;
    }

    getWindowsFileChangeScript() {
        return `# ============================================================================
# grok-edit-write-hook.ps1
# Auto-generated by CodeAgentSwarm - Do not edit manually
# ============================================================================
$ErrorActionPreference = 'SilentlyContinue'
try {
    $terminalId = $env:CODEAGENTSWARM_CURRENT_QUADRANT
    if (-not $terminalId) { exit 0 }

    $inputJson = [Console]::In.ReadToEnd()
    if (-not $inputJson) { exit 0 }
    $data = $inputJson | ConvertFrom-Json

    # camelCase first (Grok), snake_case second (Claude-shaped payloads).
    # Grok PostToolUse: toolResult (not Claude tool_response / toolResponse).
    $toolInput = if ($data.toolInput) { $data.toolInput } else { $data.tool_input }
    $toolResponse = $null
    if ($data.toolResult) { $toolResponse = $data.toolResult }
    elseif ($data.tool_result) { $toolResponse = $data.tool_result }
    elseif ($data.toolResponse) { $toolResponse = $data.toolResponse }
    elseif ($data.tool_response) { $toolResponse = $data.tool_response }
    if (-not $toolInput) { exit 0 }

    $filePath = @($toolInput.file_path, $toolInput.path, $toolInput.filePath, $toolInput.TargetFile) |
        Where-Object { $_ } | Select-Object -First 1
    if (-not $filePath) { exit 0 }

    $payload = [ordered]@{
        type            = 'file_edited'
        terminalId      = "$terminalId"
        toolName        = if ($data.toolName) { $data.toolName } else { $data.tool_name }
        filePath        = $filePath
        content         = if ($toolInput.content) { $toolInput.content } else { $toolInput.CodeContent }
        oldString       = if ($toolInput.old_string) { $toolInput.old_string } else { $toolInput.oldString }
        newString       = if ($toolInput.new_string) { $toolInput.new_string } else { $toolInput.newString }
        originalContent = if ($toolResponse -and $toolResponse.returnDisplay) { $toolResponse.returnDisplay.originalContent } elseif ($toolResponse) { $toolResponse.originalContent } else { $null }
        newContent      = if ($toolResponse -and $toolResponse.returnDisplay) { $toolResponse.returnDisplay.newContent } elseif ($toolResponse) { $toolResponse.newContent } else { $null }
    }
    $body = $payload | ConvertTo-Json -Compress -Depth 10

    # Post to THIS instance's webhook port when CodeAgentSwarm injected it; otherwise fall
    # back to the legacy dev-first (45783) / prod (45782) probe for older builds.
    $ports = if (($casPort = $env:CODEAGENTSWARM_WEBHOOK_PORT -as [int])) { @($casPort) } else { @(45783, 45782) }
    foreach ($port in $ports) {
        try {
            Invoke-RestMethod -Uri "http://127.0.0.1:$port/webhook" -Method POST -ContentType 'application/json' -Body $body -TimeoutSec 2 -ErrorAction Stop | Out-Null
            exit 0
        } catch { continue }
    }
} catch { }
exit 0
`;
    }

    /** Write a group's script file(s) to disk. */
    _writeScript(baseName, unixBody, windowsBody) {
        if (this.isWindows) {
            const p = path.join(this.hooksScriptsDir, `${baseName}.ps1`);
            fs.writeFileSync(p, windowsBody);
            return p;
        }
        const p = path.join(this.hooksScriptsDir, `${baseName}.sh`);
        fs.writeFileSync(p, unixBody, { mode: 0o755 });
        return p;
    }

    /** The `command` string that runs one of our scripts. */
    _commandFor(baseName) {
        const scriptName = this.isWindows ? `${baseName}.ps1` : `${baseName}.sh`;
        const scriptPath = this.toUnixPath(path.join(this.hooksScriptsDir, scriptName));
        if (this.isWindows) {
            return `powershell.exe -ExecutionPolicy Bypass -File '${scriptPath}'`;
        }
        return `/bin/bash '${scriptPath}'`;
    }

    // ============================================================
    // Discrete JSON hook files
    // ============================================================

    /** Absolute path of a group's JSON hook file. */
    _hookFilePath(group) {
        const file = HOOK_FILES[group];
        if (!file) throw new Error(`Unknown hook group: ${group}`);
        return path.join(this.hooksJsonDir, file);
    }

    _tagFor(group) {
        if (group === 'notifications') return GrokHooksManager.NOTIFY_TAG;
        if (group === 'titleGate') return GrokHooksManager.GATE_TAG;
        if (group === 'fileChange') return GrokHooksManager.FILECHANGE_TAG;
        throw new Error(`Unknown hook group: ${group}`);
    }

    /**
     * Build the JSON document for one group.
     * @param {string} group - 'notifications' | 'titleGate' | 'fileChange'
     * @returns {object}
     */
    _buildGroupConfig(group) {
        const entry = (command, { matcher = null, timeout = 30 } = {}) => {
            const item = { hooks: [{ type: 'command', command, timeout }] };
            if (matcher) item.matcher = matcher;
            return item;
        };

        if (group === 'notifications') {
            const cmd = this._commandFor('grok-notify-hook');
            return {
                hooks: {
                    Stop: [entry(cmd, { timeout: 5 })],
                    PermissionDenied: [entry(cmd, { timeout: 5 })],
                }
            };
        }
        if (group === 'titleGate') {
            return {
                hooks: {
                    PreToolUse: [entry(this._commandFor('grok-title-gate-hook'), { matcher: '*', timeout: 30 })],
                }
            };
        }
        if (group === 'fileChange') {
            return {
                hooks: {
                    PostToolUse: [entry(this._commandFor('grok-edit-write-hook'), { matcher: 'search_replace|Write|Edit', timeout: 10 })],
                }
            };
        }
        throw new Error(`Unknown hook group: ${group}`);
    }

    /**
     * Idempotently (re)write one group's JSON hook file.
     */
    async _installGroup(group, writeScripts) {
        try {
            await this.ensureHooksDirectory();
            await this.ensureConfigDirectory();
            writeScripts();

            const config = this._buildGroupConfig(group);
            fs.writeFileSync(this._hookFilePath(group), `${JSON.stringify(config, null, 2)}\n`, 'utf8');
            return { success: true };
        } catch (error) {
            console.error(`[GrokHooksManager] Error installing ${group}:`, error);
            return { success: false, error: error.message };
        }
    }

    /**
     * Remove one group by deleting its JSON file. The SCRIPTS are intentionally left
     * in ~/.codeagentswarm/hooks: they are shared across agents and harmless when
     * nothing references them.
     */
    async _removeGroup(group) {
        try {
            const filePath = this._hookFilePath(group);
            if (!fs.existsSync(filePath)) return { success: true };
            fs.unlinkSync(filePath);
            return { success: true };
        } catch (error) {
            console.error(`[GrokHooksManager] Error removing ${group}:`, error);
            return { success: false, error: error.message };
        }
    }

    /** True when the group's JSON file exists AND still points at OUR script. */
    async _hasGroup(group) {
        try {
            const filePath = this._hookFilePath(group);
            if (!fs.existsSync(filePath)) return false;
            const content = fs.readFileSync(filePath, 'utf8');
            return content.includes(this._tagFor(group));
        } catch (error) {
            return false;
        }
    }

    // ============================================================
    // Granular hook groups (contract required by HookSystemPreferences —
    // the has* methods are called UNGUARDED, all must exist)
    // ============================================================

    async installNotificationsHooks() {
        return this._installGroup('notifications', () =>
            this._writeScript('grok-notify-hook', this.getUnixNotifyScript(), this.getWindowsNotifyScript()));
    }

    async removeNotificationsHooks() {
        return this._removeGroup('notifications');
    }

    async hasNotificationsHooks() {
        return this._hasGroup('notifications');
    }

    async installTitleGateHooks() {
        return this._installGroup('titleGate', () => this.createTitleGateScript());
    }

    async removeTitleGateHooks() {
        return this._removeGroup('titleGate');
    }

    async hasTitleGateHooks() {
        return this._hasGroup('titleGate');
    }

    async installFileChangeHooks() {
        return this._installGroup('fileChange', () =>
            this._writeScript('grok-edit-write-hook', this.getUnixFileChangeScript(), this.getWindowsFileChangeScript()));
    }

    async removeFileChangeHooks() {
        return this._removeGroup('fileChange');
    }

    async hasFileChangeHooks() {
        return this._hasGroup('fileChange');
    }

    // ============================================================
    // Aggregate operations
    // ============================================================

    async installHooks() {
        const notif = await this.installNotificationsHooks();
        const gate = await this.installTitleGateHooks();
        const files = await this.installFileChangeHooks();
        const ok = notif.success && gate.success && files.success;
        return ok ? { success: true } : { success: false, error: notif.error || gate.error || files.error };
    }

    async removeHooks() {
        const notif = await this.removeNotificationsHooks();
        const gate = await this.removeTitleGateHooks();
        const files = await this.removeFileChangeHooks();
        const ok = notif.success && gate.success && files.success;
        return ok ? { success: true } : { success: false, error: notif.error || gate.error || files.error };
    }

    /**
     * Status snapshot. PURE DISK READ — no subprocess — so it can never hang the
     * e2e sandbox.
     */
    async checkHooksStatus() {
        const hasNotifyHook = await this.hasNotificationsHooks();
        const hasFileChangeTracking = await this.hasFileChangeHooks();
        const hasTitleGate = await this.hasTitleGateHooks();
        return {
            installed: hasNotifyHook,
            hasNotifyHook,
            hasFileChangeTracking,
            hasTitleGate,
            hasPreToolHook: hasTitleGate,
            hasPostToolHook: hasFileChangeTracking,
            settingsPath: this.hooksJsonDir,
        };
    }

    /**
     * Boot-time reconciliation: make sure the script FILES exist for every group whose
     * JSON hook file references them (the scripts may have been wiped by a reinstall).
     */
    async ensureHookScripts() {
        try {
            await this.ensureHooksDirectory();
            if (await this.hasTitleGateHooks()) this.createTitleGateScript();
            if (await this.hasNotificationsHooks()) {
                this._writeScript('grok-notify-hook', this.getUnixNotifyScript(), this.getWindowsNotifyScript());
            }
            if (await this.hasFileChangeHooks()) {
                this._writeScript('grok-edit-write-hook', this.getUnixFileChangeScript(), this.getWindowsFileChangeScript());
            }
            return { success: true };
        } catch (error) {
            return { success: false, error: error.message };
        }
    }

    /**
     * Install everything (used by the boot reconciler / first-run flow).
     */
    async ensureFullConfiguration() {
        return this.installHooks();
    }
}

module.exports = GrokHooksManager;
